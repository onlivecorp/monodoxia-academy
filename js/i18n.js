window.I18N = {
  currentLang: localStorage.getItem('monodoxia_lang') || 'az',
  
  setLanguage(lang) {
    if (!translations[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('monodoxia_lang', lang);
    document.documentElement.lang = lang;
    this.applyTranslations();
  },

  t(key) {
    const dict = translations[this.currentLang] || translations.az;
    return dict[key] || translations.az[key] || key;
  },

  applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.t(key);
      if (text) el.textContent = text;
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const text = this.t(key);
      if (text) el.setAttribute('placeholder', text);
    });

    // Update active flag or badge in UI
    const activeLangLabel = document.getElementById('current-lang-label');
    if (activeLangLabel) {
      activeLangLabel.textContent = this.currentLang.toUpperCase();
    }
  }
};
